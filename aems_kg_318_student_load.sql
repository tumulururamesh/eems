-- ---------------------------------------------------------
-- POST-LOAD VALIDATION
-- Abort/rollback automatically if any expected count fails.
-- ---------------------------------------------------------

DO $$
DECLARE
    v_master integer;
    v_year integer;
    v_assignment integer;
    v_gs integer;
    v_ns integer;
BEGIN
    SELECT COUNT(*) INTO v_master
    FROM student_master sm
    JOIN kg_student_stage s ON s.student_code = sm.student_code;

    SELECT COUNT(*) INTO v_year
    FROM student_academic_year say
    JOIN student_master sm ON sm.student_id = say.student_id
    JOIN kg_student_stage s ON s.student_code = sm.student_code
    WHERE say.academic_year_id = 3
      AND say.status = 'ACTIVE';

    SELECT COUNT(*) INTO v_assignment
    FROM student_center_assignment sca
    JOIN student_master sm ON sm.student_id = sca.student_id
    JOIN kg_student_stage s ON s.student_code = sm.student_code
    WHERE sca.academic_year_id = 3
      AND sca.active_flag = TRUE;

    SELECT COUNT(*) FILTER (WHERE schooling_status = 'GS'),
           COUNT(*) FILTER (WHERE schooling_status = 'NS')
      INTO v_gs, v_ns
    FROM kg_student_stage;

    IF v_master <> 318 THEN
        RAISE EXCEPTION 'student_master count %, expected 318.', v_master;
    END IF;

    IF v_year <> 318 THEN
        RAISE EXCEPTION 'student_academic_year ACTIVE count %, expected 318.', v_year;
    END IF;

    IF v_assignment <> 318 THEN
        RAISE EXCEPTION 'student_center_assignment count %, expected 318.', v_assignment;
    END IF;

    IF v_gs <> 316 OR v_ns <> 2 THEN
        RAISE EXCEPTION 'GS/NS counts are %/%, expected 316/2.', v_gs, v_ns;
    END IF;
END $$;

COMMIT;

