DO $$
DECLARE
    v_count integer;
BEGIN
    SELECT COUNT(*) INTO v_count FROM kg_student_stage;
    IF v_count <> 318 THEN
        RAISE EXCEPTION 'Stage row count is %, expected 318.', v_count;
    END IF;

    SELECT COUNT(*) INTO v_count
    FROM (
        SELECT student_code
        FROM kg_student_stage
        GROUP BY student_code
        HAVING COUNT(*) > 1
    ) d;
    IF v_count <> 0 THEN
        RAISE EXCEPTION 'Duplicate student codes found in staging data.';
    END IF;

    SELECT COUNT(*) INTO v_count
    FROM kg_student_stage
    WHERE gender NOT IN ('Boy', 'Girl');
    IF v_count <> 0 THEN
        RAISE EXCEPTION 'Invalid gender values found in staging data.';
    END IF;

    SELECT COUNT(*) INTO v_count
    FROM kg_student_stage
    WHERE schooling_status NOT IN ('GS', 'NS');
    IF v_count <> 0 THEN
        RAISE EXCEPTION 'Invalid schooling_status values found.';
    END IF;

    SELECT COUNT(*) INTO v_count
    FROM kg_student_stage
    WHERE schooling_status = 'NS'
      AND (school_name IS NOT NULL
           OR school_type IS NOT NULL
           OR class_studying IS NOT NULL
           OR medium IS NOT NULL
           OR group_code IS NOT NULL);
    IF v_count <> 0 THEN
        RAISE EXCEPTION 'NS students contain school-specific academic data.';
    END IF;

    SELECT COUNT(*) INTO v_count
    FROM kg_student_stage s
    LEFT JOIN tuition_center tc
      ON tc.center_code = s.center_code
    WHERE tc.center_id IS NULL;
    IF v_count <> 0 THEN
        RAISE EXCEPTION '% staging rows refer to an unknown AVLC.', v_count;
    END IF;

    SELECT COUNT(*) INTO v_count
    FROM kg_student_stage s
    JOIN student_master sm
      ON sm.student_code = s.student_code;
    IF v_count <> 0 THEN
        RAISE EXCEPTION '% student codes already exist in student_master.', v_count;
    END IF;

    SELECT COUNT(*) INTO v_count
    FROM kg_student_stage s
    LEFT JOIN curriculum_group_master cgm
      ON cgm.group_code = s.group_code
    WHERE s.schooling_status = 'GS'
      AND s.group_code IS NOT NULL
      AND cgm.group_id IS NULL;
    IF v_count <> 0 THEN
        RAISE EXCEPTION '% GS rows have an unknown curriculum group.', v_count;
    END IF;
END $$;

